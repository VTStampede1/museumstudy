import pandas as pd

# 1. Загружаем таблицу
# Укажите здесь путь к вашему файлу
file_path = 'Экспонаты, Космос.xlsx' 
df = pd.read_excel(file_path)

# 2. Исправляем структуру данных (критически важный шаг)
# В Excel визуально понятно, что пустые ячейки в столбце B относятся к предыдущему значению.
# Pandas видит их как NaN (Not a Number/Empty). 
# Метод ffill() заполняет пустоты значениями сверху вниз.
df['Название предмета'] = df['Название предмета'].ffill()
df['Первичные актанты'] = df['Первичные актанты'].ffill()
df['Связь с первичным актантом'] = df['Связь с первичным актантом'].ffill()

# 3. Выбираем нужные столбцы по их именам (согласно заголовку файла)
# Столбец B = "Название предмета"
# Столбец D = "Первичные актанты"
# Столбец E = "Связь с первичным актантом"

# Удаляем строки, где нет целевого объекта (D), так как связь строить не с чем
df_clean = df.dropna(subset=['Первичные актанты'])

# 4. Функция очистки текста
def clean_text(text):
    if pd.isna(text):
        return ""
    # Убираем пробелы, переносы строк и меняем двойные кавычки на одинарные
    return str(text).strip().replace('"', '\\"').replace('\n', ' ')

# Списки для хранения результата
output_lines = []
seen_lines = set() # Множество для быстрой проверки дублей

# 5. Итерация по строкам
for index, row in df_clean.iterrows():
    source = clean_text(row['Название предмета'])        # Столбец B
    target = clean_text(row['Первичные актанты'])        # Столбец D
    label = clean_text(row['Связь с первичным актантом']) # Столбец E
    
    # Формируем итоговую строку
    line = f'"{source}" -> "{target}" [label="{label}"];'
    
    # 6. Проверка на уникальность
    if line not in seen_lines:
        seen_lines.add(line)      # Запоминаем, что видели эту строку
        output_lines.append(line) # Добавляем в итоговый список
        print(line)

# 7. Сохранение результата
with open('Космос (Н-ПА).txt', 'w', encoding='utf-8') as f:
    f.write('\n'.join(output_lines))

print(f"\nГотово! Обработано уникальных связей: {len(output_lines)}")
